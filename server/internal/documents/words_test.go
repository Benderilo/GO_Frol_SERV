import "testing"

// Сумма прописью стоит в счёте рядом с цифрами, и расхождение между ними
// заметят первым делом. Проверяем склонения и переходы через разряды.
func TestMoneyWords(t *testing.T) {
	cases := map[int64]string{
		0:           "Ноль рублей 00 копеек",
		1:           "Ноль рублей 01 копейка",
		2:           "Ноль рублей 02 копейки",
		5:           "Ноль рублей 05 копеек",
		11:          "Ноль рублей 11 копеек",
		100:         "Один рубль 00 копеек",
		200:         "Два рубля 00 копеек",
		500:         "Пять рублей 00 копеек",
		1_100:       "Одиннадцать рублей 00 копеек",
		2_100:       "Двадцать один рубль 00 копеек",
		199_999:     "Одна тысяча девятьсот девяносто девять рублей 99 копеек",
		100_000:     "Одна тысяча рублей 00 копеек",
		200_000:     "Две тысячи рублей 00 копеек",
		500_000:     "Пять тысяч рублей 00 копеек",
		1_100_000:   "Одиннадцать тысяч рублей 00 копеек",
		2_100_000:   "Двадцать одна тысяча рублей 00 копеек",
		15_000_000:  "Сто пятьдесят тысяч рублей 00 копеек",
		100_000_000: "Один миллион рублей 00 копеек",
		200_000_000: "Два миллиона рублей 00 копеек",
		123_456_789: "Один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь рублей 89 копеек",
		4_850_050:   "Сорок восемь тысяч пятьсот рублей 50 копеек",
		-50_000:     "Минус пятьсот рублей 00 копеек",
	}
	for kop, want := range cases {
		if got := MoneyWords(kop); got != want {
			t.Errorf("MoneyWords(%d)\n получено: %q\n ожидалось: %q", kop, got, want)
		}
	}
}

